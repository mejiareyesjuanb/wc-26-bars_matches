// Build script: geocode the curated neighborhood NAME lists in
// src/data/cityNeighborhoodNames.js into centroids, and write the generated
// src/data/cityCentroids.js (committed). Coordinates come from Google (Places
// Text Search), never hand-typed.
//
//   node scripts/build-city-neighborhoods.mjs
//
// Requires GOOGLE_MAPS_API_KEY in .env. Re-run after editing the name lists.
import 'dotenv/config'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { CITY_NEIGHBORHOODS } from '../src/data/cityNeighborhoodNames.js'

const KEY = process.env.GOOGLE_MAPS_API_KEY
if (!KEY) {
  console.error('Missing GOOGLE_MAPS_API_KEY in .env')
  process.exit(1)
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const round5 = (n) => Math.round(n * 1e5) / 1e5

// Geocode a free-text place via Places Text Search → [lat, lng] (or null).
async function geocode(query) {
  const res = await fetch('https://places.googleapis.com/v1/places:searchText', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Goog-Api-Key': KEY,
      'X-Goog-FieldMask': 'places.location,places.displayName,places.formattedAddress',
    },
    body: JSON.stringify({ textQuery: query, maxResultCount: 1 }),
  })
  if (!res.ok) throw new Error(`searchText ${res.status}: ${await res.text()}`)
  const data = await res.json()
  const loc = data.places?.[0]?.location
  return loc ? [round5(loc.latitude), round5(loc.longitude)] : null
}

const centroids = {} // cityId -> { name: [lat,lng] }
const boroughOf = {} // cityId -> { name: borough }  (two-level cities only)

for (const [cityId, cfg] of Object.entries(CITY_NEIGHBORHOODS)) {
  centroids[cityId] = {}
  const region = cfg.region ? `, ${cfg.region}` : ''
  // Flatten: flat `neighborhoods` list, or per-borough `boroughs` map.
  const entries = cfg.boroughs
    ? Object.entries(cfg.boroughs).flatMap(([borough, names]) => names.map((n) => ({ n, borough })))
    : cfg.neighborhoods.map((n) => ({ n, borough: null }))

  for (const { n, borough } of entries) {
    const query = borough
      ? `${n}, ${borough}, ${cfg.city}${region}`
      : `${n}, ${cfg.city}${region}`
    try {
      const coord = await geocode(query)
      if (!coord) {
        console.warn(`  ✗ no result: ${query}`)
        continue
      }
      centroids[cityId][n] = coord
      if (borough) {
        boroughOf[cityId] = boroughOf[cityId] || {}
        boroughOf[cityId][n] = borough
      }
      console.log(`  ✓ ${cityId} · ${n} → ${coord.join(', ')}`)
    } catch (e) {
      console.warn(`  ! error: ${query} — ${e.message}`)
    }
    await sleep(120) // be gentle on the API
  }
}

const __dirname = dirname(fileURLToPath(import.meta.url))
const out = resolve(__dirname, '../src/data/cityCentroids.js')
const banner = '// GENERATED by scripts/build-city-neighborhoods.mjs — do not edit by hand.\n' +
  '// Coordinates are Google-sourced (Places Text Search). Re-run the script to refresh.\n'
const body =
  banner +
  '\nexport const CITY_CENTROIDS = ' + JSON.stringify(centroids, null, 2) + '\n' +
  '\nexport const CITY_BOROUGH_OF = ' + JSON.stringify(boroughOf, null, 2) + '\n'
writeFileSync(out, body)
console.log(`\nWrote ${out}`)
